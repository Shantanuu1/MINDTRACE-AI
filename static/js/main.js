(async function () {
  const pill = document.getElementById("ai-pill");
  async function check() {
    try { const s = await (await fetch("/api/ai-status")).json();
      const t = s.online && s.model_available ? "AI: " + s.model + " ready" : "AI offline (fallback dialogue)";
      pill.textContent = t; pill.className = "pill " + (s.online && s.model_available ? "ok" : "bad");
      const d = document.getElementById("ai-detail"); if (d) d.textContent = s.error || "connected";
    } catch (e) { pill.textContent = "AI status unknown"; }
  }
  check(); const tb = document.getElementById("test-ai"); if (tb) tb.onclick = check;
  const chat = document.getElementById("chat"); if (!chat) return;
  const msg = document.getElementById("msg"), st = document.getElementById("status"), retry = document.getElementById("retry");
  let last = "";
  function add(cls, text, src, fb) {
    const p = document.createElement("p"); p.className = cls; p.textContent = text;
    if (src) { const s = document.createElement("span"); s.className = "src" + (fb ? " fb" : ""); s.textContent = fb ? "Predefined fallback dialogue" : "Generated by " + src; p.append(" ", s); }
    chat.append(p); p.scrollIntoView();
  }
  async function send(q) {
    last = q; retry.hidden = true; st.textContent = "Thinking…"; add("q", "You: " + q);
    try {
      const r = await fetch(chat.dataset.url, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ message: q }) });
      const d = await r.json();
      if (!r.ok) { st.textContent = d.error || "Error"; retry.hidden = false; return; }
      add("a", "Suspect: " + d.answer, d.source, d.source === "fallback");
      st.textContent = d.error ? "AI unavailable (" + d.error + "). Use Retry to ask Gemma again." : ""; retry.hidden = !d.error;
    } catch (e) { st.textContent = "Network error."; retry.hidden = false; }
  }
  document.getElementById("ask").onsubmit = e => { e.preventDefault(); const q = msg.value.trim(); if (q) { msg.value = ""; send(q); } };
  retry.onclick = () => send(last);
  document.querySelectorAll(".chip").forEach(b => b.onclick = () => send(b.dataset.q));
})();
